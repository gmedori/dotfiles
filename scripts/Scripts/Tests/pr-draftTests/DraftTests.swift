import Testing
@testable import pr_draft

@Suite("draft parsing")
struct DraftTests {
	@Test("Reads the frontmatter, the title, and the body")
	func readsDraft() throws {
		let draft = try Draft.parse("""
		---
		generated by: test
		status: submitted
		pr: '[example#7](https://github.com/gmedori/example/pull/7)'
		repo: gravitational/core
		branch: "ios/share-sheet"
		base: master
		---

		# iOS: Share sheet

		Adds a share sheet.
		""")

		#expect(draft.repo == "gravitational/core")
		#expect(draft.branch == "ios/share-sheet")
		#expect(draft.base == "master")
		#expect(draft.title == "iOS: Share sheet")
		#expect(draft.bodyLines == ["", "Adds a share sheet."])
		#expect(draft.bodyStartLine == 11)
		#expect(draft.missingProperties.isEmpty)
	}

	@Test("Lists missing and empty properties")
	func listsMissingProperties() throws {
		let draft = try Draft.parse("---\nrepo: gravitational/core\nbranch:\n---\n# iOS: Title\n")

		#expect(draft.missingProperties == ["branch", "base"])
	}

	@Test("Reads a draft without frontmatter or a title")
	func readsBareDraft() throws {
		let draft = try Draft.parse("Just a body.\n")

		#expect(draft.title == nil)
		#expect(draft.bodyLines == ["Just a body.", ""])
		#expect(draft.bodyStartLine == 1)
		#expect(draft.missingProperties == ["repo", "branch", "base"])
	}

	@Test("Rejects frontmatter that never closes")
	func rejectsUnterminatedFrontmatter() {
		#expect(throws: (any Error).self) {
			try Draft.parse("---\nrepo: gravitational/core\n# iOS: Title\n")
		}
	}
}
