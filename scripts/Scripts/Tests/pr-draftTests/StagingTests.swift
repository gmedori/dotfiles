import Foundation
import Testing
@testable import pr_draft

struct `staging a draft` {
	static let draft = """
		---
		generated by: test
		status: draft
		repo: gravitational/core
		branch: ios/share-sheet
		base: master
		---

		# iOS: Share sheet

		Adds a share sheet. See `![[Pasted image 20261118101500.png]]` for the syntax.

		```swift
		let embed = "![[shot two.png]]"
		```

		## Screenshots

		**Share sheet (before)**
		![[Pasted image 20261118101500.png]]

		![[shot two.png|Dark mode share sheet]]

		![[shot two.png|300]]

		![Recording](assets/demo%20clip.mov)

		![Logo](https://example.com/logo.png)

		![[Teleport/Images/pathy.png]]

		![[elsewhere.png]]

		**Settings, light**
		<!-- TODO: attach screenshot -->
		"""

	static let broken = """
		---
		repo: gravitational/core
		branch: ios/broken
		base: master
		---

		# iOS: Broken

		![[Some Note]]

		![[dup.png]]

		![[missing.png]]

		![[clip.webp]]
		"""

	let vault: TemporaryVault
	let draftFile: URL
	let brokenFile: URL
	let stage: URL

	init() throws {
		self.vault = try TemporaryVault()
		for path in [
			"Teleport/PR Drafts/assets/Pasted image 20261118101500.png",
			"Teleport/PR Drafts/assets/shot two.png",
			"Teleport/PR Drafts/assets/demo clip.mov",
			"Teleport/PR Drafts/assets/clip.webp",
			"Teleport/Images/pathy.png",
			"Other/elsewhere.png",
			"Other/dup.png",
			"More/dup.png",
		] {
			try vault.write(path)
		}
		self.draftFile = try vault.write("Teleport/PR Drafts/2026-11-18 ios-share-sheet.md", Self.draft)
		self.brokenFile = try vault.write("Teleport/PR Drafts/2026-11-18 ios-broken.md", Self.broken)
		self.stage = vault.root.appending(path: "stage", directoryHint: .isDirectory)
	}

	func prepare(_ file: URL, alt: [Int: String] = [:]) throws -> PreparedDraft {
		try Staging.prepare(draft: file, altOverrides: alt, stageDirectory: stage)
	}

	@Test
	func `Stages every embedded file once, in the order they first appear`() throws {
		let prepared = try prepare(draftFile)

		#expect(prepared.ok, "\(prepared.errors)")
		#expect(prepared.attachments.map { [$0.source, $0.staged, $0.kind.rawValue] } == [
			[
				"Teleport/PR Drafts/assets/Pasted image 20261118101500.png",
				"./01-pasted-image-20261118101500.png",
				"image",
			],
			["Teleport/PR Drafts/assets/shot two.png", "./02-shot-two.png", "image"],
			["Teleport/PR Drafts/assets/demo clip.mov", "./03-demo-clip.mov", "video"],
			["Teleport/Images/pathy.png", "./04-pathy.png", "image"],
			["Other/elsewhere.png", "./05-elsewhere.png", "image"],
		])
		for attachment in prepared.attachments {
			let copy = stage.appending(path: String(attachment.staged.dropFirst(2)))
			#expect(try vault.read(copy) == attachment.source)
		}
	}

	@Test
	func `Rewrites embeds and leaves code, comments, and URLs as written`() throws {
		let prepared = try prepare(draftFile)
		let body = try vault.read(URL(filePath: prepared.bodyFile))

		#expect(body == """
			Adds a share sheet. See `![[Pasted image 20261118101500.png]]` for the syntax.

			```swift
			let embed = "![[shot two.png]]"
			```

			## Screenshots

			**Share sheet (before)**
			![Share sheet (before)](./01-pasted-image-20261118101500.png)

			![Dark mode share sheet](./02-shot-two.png)

			![Dark mode share sheet](./02-shot-two.png)

			![](./03-demo-clip.mov)

			![Logo](https://example.com/logo.png)

			![](./04-pathy.png)

			![](./05-elsewhere.png)

			**Settings, light**
			<!-- TODO: attach screenshot -->

			""")
	}

	@Test
	func `Reports where alt text came from, the placeholders, and the images without alt text`() throws {
		let prepared = try prepare(draftFile)

		#expect(prepared.attachments.map(\.alt) == ["Share sheet (before)", "Dark mode share sheet", nil, nil, nil])
		#expect(prepared.attachments.map(\.altFrom) == [.label, .embed, nil, nil, nil])
		#expect(prepared.needsAlt == [4, 5])
		#expect(prepared.placeholders == ["Settings, light"])
		#expect(prepared.title == "iOS: Share sheet")
	}

	@Test
	func `Uses alt text from --alt over the draft's`() throws {
		let prepared = try prepare(draftFile, alt: [1: "Old share sheet", 5: "Settings tab"])
		let body = try vault.read(URL(filePath: prepared.bodyFile))

		#expect(prepared.attachments.map(\.attachArgument) == [
			"./01-pasted-image-20261118101500.png#Old share sheet",
			"./02-shot-two.png#Dark mode share sheet",
			"./03-demo-clip.mov",
			"./04-pathy.png",
			"./05-elsewhere.png#Settings tab",
		])
		#expect(prepared.attachments[0].altFrom == .option)
		#expect(prepared.needsAlt == [4])
		#expect(body.contains("![Old share sheet](./01-pasted-image-20261118101500.png)"))
		#expect(body.contains("![Settings tab](./05-elsewhere.png)"))
	}

	@Test
	func `Reports --alt numbers that no attachment has`() throws {
		let prepared = try prepare(draftFile, alt: [9: "Nothing"])

		#expect(prepared.errors == ["`--alt` gives alt text for 9, but the body has no attachment with that number."])
	}

	@Test
	func `Reports the embeds it can't stage and leaves them as written`() throws {
		let prepared = try prepare(brokenFile)
		let body = try vault.read(URL(filePath: prepared.bodyFile))

		#expect(!prepared.ok)
		#expect(prepared.errors == [
			"Line 9 embeds `![[Some Note]]`, which isn't an image or video GitHub accepts. GitHub accepts .png, .jpg, .jpeg, .gif, and .svg images and .mp4, .mov, and .webm videos.",
			"Line 11 embeds `![[dup.png]]`, but more than one file matches it (`More/dup.png`, `Other/dup.png`). Link it by its path from the vault root.",
			"Line 13 embeds `![[missing.png]]`, but no file in the vault matches it.",
			"Line 15 embeds `![[clip.webp]]`, which isn't an image or video GitHub accepts. GitHub accepts .png, .jpg, .jpeg, .gif, and .svg images and .mp4, .mov, and .webm videos.",
		])
		#expect(body == "![[Some Note]]\n\n![[dup.png]]\n\n![[missing.png]]\n\n![[clip.webp]]\n")
		#expect(prepared.attachments.isEmpty)
	}

	@Test
	func `Reports missing frontmatter and a missing title`() throws {
		try "Body only\n".write(to: brokenFile, atomically: true, encoding: .utf8)
		let prepared = try prepare(brokenFile)

		#expect(prepared.errors == [
			"The frontmatter is missing `repo`, `branch`, and `base`.",
			"The draft has no title line starting with `# `.",
		])
	}

	@Test
	func `Replaces the staging folder and round-trips the manifest`() throws {
		try FileManager.default.createDirectory(at: stage, withIntermediateDirectories: true)
		try "stale".write(to: stage.appending(path: "stale.png"), atomically: true, encoding: .utf8)

		var prepared = try prepare(draftFile)
		prepared.ghSupportsAttach = true
		try Staging.saveManifest(prepared)

		#expect(!FileManager.default.fileExists(atPath: stage.appending(path: "stale.png").path(percentEncoded: false)))
		#expect(try Staging.loadManifest(from: stage) == prepared)
		let json = try JSON.encode(prepared)
		#expect(json.contains("\"needs_alt\" : ["))
		#expect(json.contains("\"alt_from\" : \"label\""))
		#expect(json.contains("\"gh_supports_attach\" : true"))
	}

	@Test
	func `Gives a video alone on its line a paragraph of its own`() throws {
		try """
			---
			repo: gravitational/core
			branch: ios/videos
			base: master
			---

			# iOS: Videos

			**Share sheet, recorded**
			![[demo clip.mov]]
			The sheet slides up.

			Inline, ![[demo clip.mov]] stays in its sentence.

			> ![[demo clip.mov]]
			""".write(to: brokenFile, atomically: true, encoding: .utf8)

		let prepared = try prepare(brokenFile)
		let body = try vault.read(URL(filePath: prepared.bodyFile))

		#expect(body == """
			**Share sheet, recorded**

			![](./01-demo-clip.mov)

			The sheet slides up.

			Inline, ![](./01-demo-clip.mov) stays in its sentence.

			> ![](./01-demo-clip.mov)

			""")
	}

	@Test
	func `Names staged copies with lowercase words and hyphens`() {
		#expect(BodyRewriter.slug("Pasted image 20261118101500") == "pasted-image-20261118101500")
		#expect(BodyRewriter.slug("  Été — Résumé!  ") == "t-r-sum")
		#expect(BodyRewriter.slug("日本") == "file")
		#expect(BodyRewriter.slug(String(repeating: "a", count: 39) + " b c", limit: 40) == String(
			repeating: "a",
			count: 39,
		))
	}
}
